#!/usr/bin/env bash
#
# Keyhole installer for Proxmox VE.
#
# Creates an unprivileged Debian 12 container, installs a signed release, and
# leaves you with a URL to set up the first administrator.
#
# Piping a script to a shell is precisely the risk a password manager exists to
# defend against, so: this file pins a release tag rather than main; it verifies
# the binary against a signature made by the key printed below, which you can
# compare against the one in the repository README; and it prints everything it
# is going to do before it does any of it.
#
# The way to run it that lets you check all of that first:
#
#   curl -fsSLO https://raw.githubusercontent.com/ssan9876/keyhole/v1.0.0/scripts/install.sh
#   less install.sh          # read it
#   bash install.sh
#
# --dry-run prints the whole plan and touches nothing. It needs no Proxmox
# host, so you can read the plan on your laptop before running it for real.
set -euo pipefail

OWNER="ssan9876"
REPO="keyhole"
VERSION="v1.0.0"
readonly OWNER REPO VERSION

# The release signing key. Compare it against the README before trusting this
# script — if they differ, stop.
#
# THIS IS A PLACEHOLDER. The keypair is generated by the repository owner with
# `minisign -G`; the secret half becomes the MINISIGN_SECRET_KEY repository
# secret and the public half goes here and in the README. Until it is replaced
# this script refuses to install anything (see check_signing_key), because an
# installer that quietly skips verification is worse than one that does not
# run at all.
#
# Filling in the real key is not only an edit to the line below. The tests know
# about the placeholder in two ways, and both go red the moment it is replaced:
#
#   - both goldens in scripts/testdata/ record this key and the warning block
#     print_plan emits for it, so regenerate them by rerunning the two commands
#     at the top of scripts/install_test.sh with their output redirected over
#     the .golden files, and read the diff before committing it;
#   - scripts/install_test.sh asserts that a real run refuses to start on a
#     placeholder key, which a real key makes untestable here — that assertion
#     goes away with the placeholder.
readonly MINISIGN_PUBKEY="RWQ...replace-with-the-real-key..."

readonly TEMPLATE_STORAGE="local"
readonly SERVICE_USER="keyhole"
readonly DATA_DIR="/var/lib/keyhole"
readonly CONFIG_DIR="/etc/keyhole"
readonly PORT="8477"

readonly TUNNEL_TOKEN_PATH="${CONFIG_DIR}/tunnel-token"
readonly WORK_DIR="/tmp/keyhole-install"

CTID=""; HOSTNAME_CT="keyhole"; CORES="2"; RAM="1024"; DISK="8"
STORAGE="local-lvm"; BRIDGE="vmbr0"; NETWORK=""; TUNNEL_TOKEN_FILE=""
HOSTNAME_EXTERNAL=""; ADMIN_EMAIL=""; DRY_RUN="no"; ASSUME_YES="no"
# Snapshots the nightly timer keeps. Matches defaultBackupKeep in
# cmd/keyhole/backup.go; 0 means keep every snapshot forever.
BACKUP_KEEP="14"

# Derived from the above once the flags and prompts have settled.
TUNNEL_TOKEN=""; ADDR=""; BASE_URL=""; BASE_URL_HUMAN=""; HEALTH_URL=""
HEALTH_CURL_FLAGS=""; TEMPLATE=""; TLS_FINGERPRINT=""; ADMIN_OUTPUT=""
CT_ADDR=""

die() { printf 'keyhole: %s\n' "$*" >&2; exit 1; }
note() { printf '  %s\n' "$*"; }

# Every side effect goes through run(), which is what makes --dry-run a real plan
# rather than an approximation that drifts from what the script does.
run() {
  if [ "$DRY_RUN" = "yes" ]; then
    printf 'RUN: %s\n' "$*"
    return 0
  fi
  "$@"
}

# For commands that must run inside the container.
in_ct() { run pct exec "$CTID" -- "$@"; }

# Write a file inside the container. The content travels inside the command
# string rather than on a pipe so that it goes through run() like everything
# else — which means --dry-run shows you the exact bytes of every config file
# and unit this script would write. Secrets never come through here; see
# push_tunnel_token.
ct_write() {
  local path="$1" mode="$2" owner="$3" content="$4"
  in_ct sh -c "set -eu
umask 077
cat > '${path}' <<'KEYHOLE_EOF'
${content}
KEYHOLE_EOF
chown '${owner}' '${path}'
chmod '${mode}' '${path}'"
}

# Verification failure must not leave a container that is half-provisioned and
# running: an unverified binary that never got installed is harmless, a running
# container that someone later assumes is a working vault is not.
abort_stopped() {
  printf 'keyhole: %s\n' "$*" >&2
  printf 'keyhole: stopping container %s. Nothing was installed; inspect it with\n' "$CTID" >&2
  printf '         "pct start %s && pct enter %s", or remove it with "pct destroy %s".\n' \
    "$CTID" "$CTID" "$CTID" >&2
  # pct stop loses to a config lock or a concurrent pct operation often enough
  # that swallowing its status is not acceptable here: the three lines above
  # have already told the operator the container is being stopped, and someone
  # who walks away from a running, half-provisioned container believing it is
  # stopped was misled by this script rather than by the failure.
  if ! run pct stop "$CTID"; then
    printf 'keyhole: pct stop %s FAILED — the container is still running; stop it yourself\n' \
      "$CTID" >&2
  fi
  exit 1
}

is_placeholder_key() {
  case "$MINISIGN_PUBKEY" in
    *replace-with-the-real-key*) return 0 ;;
    *) return 1 ;;
  esac
}

# An installer that silently skips verification because nobody filled in the key
# is the worst outcome this file has. Refuse early, and say exactly what to fix.
check_signing_key() {
  if ! is_placeholder_key; then
    return 0
  fi
  if [ "$DRY_RUN" = "yes" ]; then
    return 0
  fi
  die "the release signing key in this script is still a placeholder.
       Replace MINISIGN_PUBKEY near the top of this file with the public key
       published in the ${OWNER}/${REPO} README (one line, beginning \"RW\"),
       then run this again. Without it nothing downloaded can be verified,
       and this script will not install an unverified binary."
}

